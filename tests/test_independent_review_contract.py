"""Проверяет поставляемый текст обязательного порядка, не поведение модели."""
import os
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'modules/core/data/ai/architecture.md'

class IndependentReviewContractTests(unittest.TestCase):
    def test_distributed_rule_keeps_independent_acceptance_contract(self):
        path = Path(os.environ.get('REVIEW_CONTRACT_SOURCE', str(SOURCE)))
        text = path.read_text(encoding='utf-8')
        heading = '## Независимая проверка по уровню риска'
        self.assertTrue(heading in text, "нет раздела независимой приёмки")
        section = text.split(heading, 1)[1].split('\n## ', 1)[0]
        compact = ' '.join(section.split())
        required = (
            'при сомнении берите более высокий уровень',
            'мелкие исправления формулировок инструкций без изменения поведения',
            'независимая приёмка не нужна. Код и правки, меняющие поведение агента, относятся к уровню 2',
            'Уровень 2 — код, синхронизация с внешними приложениями, записи задач, обычные записи в календарь',
            'правила безопасности, подтверждения и доступа. Нужны тесты и одна независимая приёмка',
            'повтор — только после вердикта «исправить»',
            'Уровень 3 — удаление данных и массовые изменения во внешних приложениях',
            'Мутационное подтверждение каждого нового теста обязательно на любом уровне',
            'Правила ниже относятся к уровням 2 и 3',
            'отдельный агент или сеанс с новым контекстом, который не создавал результат',
            'самостоятельно сверяет фактический результат',
            'Только «принято» разрешает сообщить о готовности',
            'После содержательных исправлений по вердикту «исправить» повторите независимую проверку',
            'Если отдельный проверяющий недоступен, приёмка не пройдена',
            'не расширяет доступ к проектам и секретам',
            'не запускают бесконечную цепочку проверки самих себя',
        )
        for clause in required:
            with self.subTest(clause=clause):
                self.assertIn(clause, compact)
